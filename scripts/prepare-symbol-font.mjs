// Include only the Japanese font shards needed by the game's chakra/village
// symbols, rather than loading the entire CJK family or a third-party CDN.
import { readFile, writeFile } from "node:fs/promises";

const characters = new Set([..."火水雷風土氷影音奥葉砂霧雲石雨忍"].map((char) => char.codePointAt(0)));
const css = await readFile("node_modules/@fontsource/noto-sans-jp/500.css", "utf8");
const faces = [];
for (const face of css.matchAll(/@font-face\s*\{([^}]+)\}/g)) {
  const ranges = face[1].match(/unicode-range:\s*([^;]+)/)?.[1];
  if (!ranges) continue;
  const covered = [...characters].filter((code) => ranges.split(",").some((range) => {
    const [start, end = start] = range.trim().replace(/^U\+/i, "").split("-").map((value) => parseInt(value, 16));
    return code >= start && code <= end;
  }));
  if (!covered.length) continue;
  const file = face[1].match(/url\(\.\/files\/([^)]*\.woff2)\)/)[1];
  faces.push(`@font-face {\n  font-family: "Noto Sans JP";\n  font-style: normal;\n  font-weight: 500;\n  font-display: swap;\n  src: url("@fontsource/noto-sans-jp/files/${file}") format("woff2");\n  unicode-range: ${covered.map((code) => "U+" + code.toString(16).toUpperCase()).join(", ")};\n}`);
}
await writeFile("css/symbols.css", "/* Generated by scripts/prepare-symbol-font.mjs · Noto Sans JP (SIL OFL 1.1). */\n" + faces.join("\n") + "\n");
console.log(`Prepared ${faces.length} font shards for ${characters.size} symbols.`);
